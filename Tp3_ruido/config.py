def entradas_con_ruido(X_limpia, probabilidad_ruido=0.02):
 
    X_ruidosa = np.zeros_like(X_limpia)
    
    for i in range(len(X_limpia)):
        caracter_limpio = X_limpia[i]
        caracter_ruidoso = []

        for pixel in caracter_limpio:
            if np.random.rand() < probabilidad_ruido:
                pixel_invertido = 1.0 if pixel == 0.0 else 0.0
                caracter_ruidoso.append(pixel_invertido)
            else:
                caracter_ruidoso.append(pixel)
                
        X_ruidosa[i] = caracter_ruidoso
        
    return X_ruidosa.astype(np.float32)

