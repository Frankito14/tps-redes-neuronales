def generar_ruido(matriz_base,probabilidad_ruido):
    matriz_ruidosa = []
    for letra in matriz_base:
        letra_ruidosa = []
        for bit in letra:
            if random.random() < probabilidad_ruido:
                bit_invertido = 1 - bit
                letra_ruidosa.append(bit_invertido)
            else: 
                letra_ruidosa.append(bit)
        matriz_ruidosa.append(letra_ruidosa)
        #print("ruidosa",letra_ruidosa)
        #print("normal",letra)
    return np.array(matriz_ruidosa)
    
        
